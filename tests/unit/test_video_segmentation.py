"""
Functional tests for the video segmentation MCP server (port 8009).

Calls the MCP server via HTTP. Requires both vlm-segmentation (8008) and
video-segmentation (8009) containers to be running.

Run inside agents-orchestrator container:
  pytest tests/unit/test_video_segmentation.py -v
"""

from __future__ import annotations

from pathlib import Path

import pytest


@pytest.fixture(scope="module")
def mcp_client_factory(video_segmentation_mcp_url: str):
    try:
        from videosearcher_agents.mcp_streamable_client import create_mcp_client
        return create_mcp_client, video_segmentation_mcp_url
    except ImportError as exc:
        pytest.skip(f"MCP client not importable: {exc}")


@pytest.fixture(scope="module")
def short_video(lionandgorilla_15s: str) -> str:
    """
    15-second clip from lionandgorilla.mp4.
    Using a short clip keeps video segmentation test time manageable (GPU-heavy).
    Generated by the session-scoped lionandgorilla_15s fixture in conftest.py.
    """
    return lionandgorilla_15s


