@pytest.mark.asyncio
async def test_video_mode_creates_output_file(mcp_client_factory, short_video):
    create_mcp_client, url = mcp_client_factory
    async with create_mcp_client(url) as client:
        result = await client.call_tool(
            "segment_video",
            {
                "video_path": short_video,
                "text_query": "animal",
                "output_mode": "video",
                "frame_mode": "sampled",
                "fps": 1,
                "max_frames": 5,
            },
        )
    assert isinstance(result, dict), "segment_video must return a dict"
    assert result.get("success") is True, f"Expected success=True, got: {result}"
    out_path = result.get("segmented_video_path")
    assert out_path, "video mode must return segmented_video_path"
    assert Path(out_path).exists(), f"Output video does not exist: {out_path}"
    assert Path(out_path).stat().st_size > 0, "Output video must not be empty"


@pytest.mark.asyncio
async def test_frames_mode_creates_output_dir(mcp_client_factory, short_video):
    create_mcp_client, url = mcp_client_factory
    async with create_mcp_client(url) as client:
        result = await client.call_tool(
            "segment_video",
            {
                "video_path": short_video,
                "text_query": "animal",
                "output_mode": "frames",
                "frame_mode": "sampled",
                "fps": 1,
                "max_frames": 3,
            },
        )
    assert result.get("success") is True, f"Expected success=True, got: {result}"
    out_dir = result.get("segmented_frames_dir")
    assert out_dir, "frames mode must return segmented_frames_dir"
    assert Path(out_dir).is_dir(), f"Output dir does not exist: {out_dir}"
    frames = list(Path(out_dir).glob("*.jpg")) + list(Path(out_dir).glob("*.png"))
    assert len(frames) > 0, "frames dir must contain at least one image"


@pytest.mark.asyncio
async def test_sampled_produces_fewer_frames_than_all(mcp_client_factory, short_video):
    create_mcp_client, url = mcp_client_factory

    async with create_mcp_client(url) as client:
        sampled = await client.call_tool(
            "segment_video",
            {
                "video_path": short_video,
                "text_query": "animal",
                "output_mode": "frames",
                "frame_mode": "sampled",
                "fps": 1,
                "max_frames": 3,
            },
        )

    async with create_mcp_client(url) as client:
        all_frames = await client.call_tool(
            "segment_video",
            {
                "video_path": short_video,
                "text_query": "animal",
                "output_mode": "frames",
                "frame_mode": "all",
                "max_frames": 99,
            },
        )

    n_sampled = sampled.get("total_frames", 0)
    n_all = all_frames.get("total_frames", 0)

    if n_all > 0:
        assert n_sampled <= n_all, (
            f"Sampled mode ({n_sampled}) should produce ≤ all-frames mode ({n_all})"
        )
