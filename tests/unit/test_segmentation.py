"""
Functional tests for the VLM segmentation pipeline.

These tests call GroundingDinoSam2Pipeline directly (no HTTP) so they
are fast and can run without the MCP server container running.
Requires GPU and VLMs-Testing-Framework to be on sys.path (/vlm_src).

Run inside agents-orchestrator container:
  pytest tests/unit/test_segmentation.py -v
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import pytest

# VLMs-Testing-Framework is mounted at /vlm_src inside the container
_VLM_SRC = os.getenv("VLM_SRC_PATH", "/vlm_src")
if _VLM_SRC not in sys.path:
    sys.path.insert(0, _VLM_SRC)


@pytest.fixture(scope="module")
def pipeline():
    """Load GroundingDINO + SAM2 once for all tests in this module."""
    try:
        from SegmentationPipelines import GroundingDinoSam2Pipeline
    except ImportError:
        pytest.skip("GroundingDinoSam2Pipeline not available (VLM_SRC_PATH not set?)")

    p = GroundingDinoSam2Pipeline()
    p.load_model()
    return p


@pytest.fixture(scope="module")
def sample_image(lionandgorilla_frame0: str) -> str:
    """
    Pre-extracted reference frame from lionandgorilla.mp4.
    Generated by the session-scoped lionandgorilla_frame0 fixture in conftest.py.
    Using a pre-extracted frame makes segmentation unit tests independent of
    the frame-extraction MCP server.
    """
    return lionandgorilla_frame0


# ---------------------------------------------------------------------------
# Tests
# ---------------------------------------------------------------------------

def test_masks_mode_returns_mask_paths(pipeline, sample_image, data_dir, tmp_path):
    from Samples import SegmentationSample

    sample = SegmentationSample(
        sample_id="test_lion",
        image=sample_image,
        text_queries=["lion"],
    )
    result = pipeline.predict(
        sample,
        output_mode="masks",
        output_dir=str(tmp_path),
    )

    assert isinstance(result, dict), "predict() must return a dict"
    assert "masks" in result or "mask_paths" in result, (
        "masks output mode must return masks or mask_paths"
    )


def test_segmented_image_mode_returns_image_path(pipeline, sample_image, tmp_path):
    from Samples import SegmentationSample

    sample = SegmentationSample(
        sample_id="test_gorilla",
        image=sample_image,
        text_queries=["gorilla"],
    )
    out_path = str(tmp_path / "segmented.png")
    result = pipeline.predict(
        sample,
        output_mode="segmented_image",
        output_image_path=out_path,
    )

    assert isinstance(result, dict)
    assert Path(out_path).exists(), "segmented_image output file must be created"
    assert Path(out_path).stat().st_size > 0


def test_empty_text_query_returns_graceful_result(pipeline, sample_image, tmp_path):
    from Samples import SegmentationSample

    sample = SegmentationSample(
        sample_id="test_empty",
        image=sample_image,
        text_queries=[],
    )
    # Should not raise — empty query may return empty masks
    result = pipeline.predict(sample, output_mode="masks", output_dir=str(tmp_path))
    assert isinstance(result, dict)


def test_nonexistent_image_returns_error(pipeline, tmp_path):
    from Samples import SegmentationSample

    sample = SegmentationSample(
        sample_id="test_missing",
        image="/nonexistent/path/image.jpg",
        text_queries=["cat"],
    )
    try:
        result = pipeline.predict(sample, output_mode="masks", output_dir=str(tmp_path))
        # If it returns rather than raises, it should signal failure
        assert not result.get("success", True) or result.get("error"), (
            "Missing image should produce an error result"
        )
    except (FileNotFoundError, ValueError):
        pass  # Raising is also acceptable
