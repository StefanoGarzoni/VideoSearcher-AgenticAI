@pytest.mark.asyncio
async def test_vqa_returns_nonempty_answer(vqa_tool, sample_frame):
    result = await vqa_tool(
        frame_path=sample_frame,
        question="What is the main subject of this image?",
    )
    assert isinstance(result, dict), "VQA tool must return a dict"
    assert result.get("success") is True, f"Expected success=True, got: {result}"
    answer = result.get("answer", "")
    assert isinstance(answer, str) and len(answer.strip()) > 0, (
        "answer must be a non-empty string"
    )


@pytest.mark.asyncio
async def test_vqa_missing_frame_returns_failure(vqa_tool):
    result = await vqa_tool(
        frame_path="/nonexistent/frame.jpg",
        question="What is in this image?",
    )
    assert isinstance(result, dict)
    assert result.get("success") is False, (
        "Missing frame path must return success=False"
    )
    assert result.get("error"), "Missing frame must include an error message"


@pytest.mark.asyncio
async def test_vqa_result_contains_expected_fields(vqa_tool, sample_frame):
    result = await vqa_tool(
        frame_path=sample_frame,
        question="Describe what you see.",
    )
    for field in ("success", "frame_path", "question", "answer", "model"):
        assert field in result, f"VQA result must contain field '{field}'"


@pytest.mark.asyncio
async def test_vqa_frame_path_echoed_in_result(vqa_tool, sample_frame):
    result = await vqa_tool(
        frame_path=sample_frame,
        question="What color is the background?",
    )
    assert result.get("frame_path") == sample_frame, (
        "frame_path in result must match input"
    )


@pytest.mark.asyncio
async def test_vqa_answer_contains_expected_keywords(vqa_tool, sample_frame):
    """
    Behavioral contract: when asked about lionandgorilla_frame0.jpg, the VQA
    answer must mention at least one animal-related keyword.
    This is not an accuracy test — it verifies the model is reasoning about
    the visual content rather than returning a generic or empty response.
    """
    _KEYWORDS = ("lion", "gorilla", "animal", "cat", "primate", "ape", "feline", "mammal")
    result = await vqa_tool(
        frame_path=sample_frame,
        question="What animals are visible in this image?",
    )
    assert result.get("success") is True, f"VQA tool failed: {result}"
    answer = result.get("answer", "").lower()
    assert len(answer.strip()) >= 5, "Answer is too short to be meaningful"
    assert any(kw in answer for kw in _KEYWORDS), (
        f"Answer does not mention any expected animal keyword {_KEYWORDS}. "
        f"Got: {answer!r}"
    )
