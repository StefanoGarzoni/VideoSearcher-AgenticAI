import pytest


@pytest.fixture(scope="module")
def vqa_tool():
    try:
        from videosearcher_agents.specialized.vqa_agent import answer_visual_question_tool
        return answer_visual_question_tool
    except ImportError as exc:
        pytest.skip(f"VQA agent not importable: {exc}")


@pytest.fixture(scope="module")
def sample_frame(lionandgorilla_frame0: str) -> str:
    """
    Pre-extracted reference frame from lionandgorilla.mp4.
    Generated by the session-scoped lionandgorilla_frame0 fixture in conftest.py.
    Using a pre-extracted frame avoids a dependency on the frame-extraction MCP server.
    """
    return lionandgorilla_frame0


